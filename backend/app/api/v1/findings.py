from datetime import datetime
from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy.orm import Session

from app.api.deps import get_db, require_auth, check_cse_access
from app.db.models.user import User
from app.schemas.finding import (
    SignalResponse,
    FindingResponse,
    ExaminerWorkspaceResponse,
    ReviewQueueResponse,
    FindingDecisionRequest,
    EvidenceDemandRequest,
)
from app.services.finding_service import FindingService

router = APIRouter(tags=["Findings & Review Queue"])


# 1. Signal Detail Retrieval (TASK GROUP 1)
@router.get("/signals/{signal_id}", response_model=SignalResponse, summary="Retrieve Analytical Signal Detail")
def get_signal_detail(
    signal_id: str,
    current_user: User = Depends(require_auth),
    db: Session = Depends(get_db),
):
    """Retrieve full analytical signal details generated by analytical engines."""
    return FindingService.get_signal(db=db, signal_id=signal_id)


# 2. Finding List & Search (TASK GROUP 4)
@router.get("/findings", response_model=List[FindingResponse], summary="Query and Filter Findings")
@router.get("/review/findings", response_model=List[FindingResponse], summary="Review Findings Alias")
def list_findings(
    cse_id: Optional[str] = Query(None, description="Filter by CSE code or ID"),
    priority: Optional[str] = Query(None, description="Filter by priority (CRITICAL, HIGH, MEDIUM, LOW)"),
    status_filter: Optional[str] = Query(None, alias="status", description="Filter by lifecycle status"),
    engine: Optional[str] = Query(None, description="Filter by detection engine"),
    control: Optional[str] = Query(None, description="Filter by control code"),
    date_from: Optional[datetime] = Query(None, description="Created after date"),
    date_to: Optional[datetime] = Query(None, description="Created before date"),
    search: Optional[str] = Query(None, description="Search keyword in title or why_flagged"),
    page: int = Query(1, ge=1),
    page_size: int = Query(50, ge=1, le=200),
    current_user: User = Depends(require_auth),
    db: Session = Depends(get_db),
):
    """Retrieve filtered and paginated list of candidate, under-review, and qualified findings."""
    return FindingService.list_findings(
        db=db,
        cse_id=cse_id,
        priority=priority,
        status_filter=status_filter,
        engine=engine,
        control=control,
        date_from=date_from,
        date_to=date_to,
        search=search,
        page=page,
        page_size=page_size,
    )


