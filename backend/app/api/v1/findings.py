# 6. Human Adjudication Actions (TASK GROUP 4 & 6)
@router.post("/findings/{finding_id}/validate", response_model=FindingResponse, summary="Validate Finding")
def validate_finding(
    finding_id: str,
    payload: Optional[FindingDecisionRequest] = None,
    current_user: User = Depends(require_auth),
    db: Session = Depends(get_db),
):
    """Human examiner action: Validates candidate finding after telemetry inspection."""
    return FindingService.apply_human_decision(
        db=db,
        finding_id=finding_id,
        target_status="VALIDATED",
        user=current_user,
        notes=payload.notes if payload else None,
        reason=payload.reason if payload else "Evidence inspection confirms discrepancy",
        action_name="VALIDATE",
    )


