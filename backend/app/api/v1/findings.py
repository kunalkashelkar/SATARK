# 7. Frontend Compatibility Adjudication Route
@router.post("/review/findings/{finding_id}/adjudicate", response_model=FindingResponse, summary="Adjudicate Finding Alias")
def adjudicate_finding_alias(
    finding_id: str,
    payload: FindingDecisionRequest,
    current_user: User = Depends(require_auth),
    db: Session = Depends(get_db),
):
    """Generic adjudication endpoint used by existing frontend client."""
    target_status = payload.status or "VALIDATED"
    return FindingService.apply_human_decision(
        db=db,
        finding_id=finding_id,
        target_status=target_status,
        user=current_user,
        notes=payload.notes,
        reason=payload.reason,
        action_name=f"ADJUDICATE_{target_status}",
    )


