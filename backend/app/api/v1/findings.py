# 4. Examiner Workspace Context (TASK GROUP 5)
@router.get("/findings/{finding_id}/workspace", response_model=ExaminerWorkspaceResponse, summary="Examiner Finding Workspace")
def get_finding_workspace(
    finding_id: str,
    current_user: User = Depends(require_auth),
    db: Session = Depends(get_db),
):
    """Retrieve complete 3-panel examiner workspace context:
    finding, why_flagged, expected_vs_observed, supporting_evidence, provenance,
    decision_history, available_actions, and remediation state.
    """
    workspace = FindingService.get_finding_workspace(db=db, finding_id=finding_id)
    check_cse_access(workspace.finding.cse_id, current_user, db)
    return workspace


